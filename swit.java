public class swit {
    public static void main(String[] args) {
        int value = 2;
        switch (value) {
            case 5:
                System.out.println("One");
                break;
            case 3:
                System.out.println("Two");
                break;
            case 3:
                System.out.println("Three");
                break;
            default:
                System.out.println("Other");
        }
    }
}
